// usersPage renders one GET /v1/users response. next is the raw JSON for
// next_page_token ("null", `"p2"`), or "" to leave the field out.
func usersPage(next string, ids ...string) string {
	users := make([]string, len(ids))
	for i, id := range ids {
		users[i] = fmt.Sprintf(`{"id":%q,"email":"%s@example.com"}`, id, id)
	}
	body := fmt.Sprintf(`{"users":[%s]`, strings.Join(users, ","))
	if next != "" {
		body += `,"next_page_token":` + next
	}
	return body + "}"
}

// TestUsersDataSourcePaging runs data "lumos_users" against a fake API and
// checks it follows next_page_token through every page, stops only when the
// token is null or missing, and fails the read when any page is an error.
//
// The paging loop is generated by Speakeasy from the overlay's
// x-speakeasy-pagination block, so this is what catches a generator upgrade
// or overlay change that alters how paging stops. It uses a fake API rather
// than a live domain because the edge cases (a short or empty page that
// still has a next token, a response with no next_page_token field) can't
// be produced on demand from real data.
func TestUsersDataSourcePaging(t *testing.T) {
	cases := []struct {
		name       string
		pages      map[string]string // page_token sent -> response body
		errorPages map[string]string // page_token sent -> body of a 400 response
		wantIDs    []string
		wantErr    string
		wantTokens []string // page_token sent on each request of one read
	}{
		{
			name: "three pages",
			pages: map[string]string{
				"":   usersPage(`"p2"`, "u1", "u2"),
				"p2": usersPage(`"p3"`, "u3", "u4"),
				"p3": usersPage("null", "u5"),
			},
			wantIDs:    []string{"u1", "u2", "u3", "u4", "u5"},
			wantTokens: []string{"", "p2", "p3"},
		},
		{
			name:       "one page",
			pages:      map[string]string{"": usersPage("null", "u1", "u2")},
			wantIDs:    []string{"u1", "u2"},
			wantTokens: []string{""},
		},
		{
			name:       "empty list",
			pages:      map[string]string{"": usersPage("null")},
			wantIDs:    []string{},
			wantTokens: []string{""},
		},
		{
			name: "short page with a next token keeps going",
			pages: map[string]string{
				"":   usersPage(`"p2"`, "u1"),
				"p2": usersPage("null", "u2", "u3"),
			},
			wantIDs:    []string{"u1", "u2", "u3"},
			wantTokens: []string{"", "p2"},
		},
		{
			name: "empty page with a next token keeps going",
			pages: map[string]string{
				"":   usersPage(`"p2"`),
				"p2": usersPage("null", "u1"),
			},
			wantIDs:    []string{"u1"},
			wantTokens: []string{"", "p2"},
		},
		{
			name:       "missing next_page_token ends the list",
			pages:      map[string]string{"": usersPage("", "u1", "u2")},
			wantIDs:    []string{"u1", "u2"},
			wantTokens: []string{""},
		},
		{
			name:       "error on a later page fails the read",
			pages:      map[string]string{"": usersPage(`"p2"`, "u1", "u2")},
			errorPages: map[string]string{"p2": `{"detail":"page token expired"}`},
			wantErr:    `status 400: {"detail":"page token expired"}`,
			wantTokens: []string{"", "p2"},
		},
	}

	for _, tc := range cases {
		t.Run(tc.name, func(t *testing.T) {
			var mu sync.Mutex
			var tokens, pageSizes []string
			server := httptest.NewServer(http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
				if r.URL.Path != "/v1/users" {
					http.NotFound(w, r)
					return
				}
				token := r.URL.Query().Get("page_token")
				mu.Lock()
				tokens = append(tokens, token)
				pageSizes = append(pageSizes, r.URL.Query().Get("page_size"))
				mu.Unlock()
				w.Header().Set("Content-Type", "application/json")
				if body, ok := tc.errorPages[token]; ok {
					w.WriteHeader(http.StatusBadRequest)
					fmt.Fprint(w, body)
					return
				}
				body, ok := tc.pages[token]
				if !ok {
					http.Error(w, "unexpected page_token "+token, http.StatusBadRequest)
					return
				}
				fmt.Fprint(w, body)
			}))
			defer server.Close()

			checks := []resource.TestCheckFunc{
				resource.TestCheckResourceAttr("data.lumos_users.all", "users.#", fmt.Sprint(len(tc.wantIDs))),
			}
			for i, id := range tc.wantIDs {
				checks = append(checks, resource.TestCheckResourceAttr("data.lumos_users.all", fmt.Sprintf("users.%d.id", i), id))
			}

			step := resource.TestStep{
				Config: fmt.Sprintf(`
provider "lumos" {
  server_url  = %q
  http_bearer = "test-token"
}

data "lumos_users" "all" {
  search_term = "example"
}
`, server.URL),
				Check: resource.ComposeAggregateTestCheckFunc(checks...),
			}
			if tc.wantErr != "" {
				step.Check = nil
				step.ExpectError = regexp.MustCompile(regexp.QuoteMeta(tc.wantErr))
			}
			resource.UnitTest(t, resource.TestCase{
				ProtoV6ProviderFactories: testAccProtoV6ProviderFactories,
				Steps:                    []resource.TestStep{step},
			})

			// Terraform reads the data source more than once per test step, so
			// the server sees the same page sequence once per read.
			mu.Lock()
			defer mu.Unlock()
			if len(tokens) == 0 || len(tokens)%len(tc.wantTokens) != 0 {
				t.Fatalf("page_token sequence %q is not whole reads of %q", tokens, tc.wantTokens)
			}
			for i := 0; i < len(tokens); i += len(tc.wantTokens) {
				if got := tokens[i : i+len(tc.wantTokens)]; !reflect.DeepEqual(got, tc.wantTokens) {
					t.Fatalf("read %d sent page_tokens %q, want %q", i/len(tc.wantTokens)+1, got, tc.wantTokens)
				}
			}
			for _, size := range pageSizes {
				if size != "100" {
					t.Fatalf("sent page_size %q, want \"100\" on every request", size)
				}
			}
		})
	}
}

// TestAccUsersDataSource looks up the token's own user by email, so it
// needs no fixture users in the test domain.
func TestAccUsersDataSource(t *testing.T) {
	resource.Test(t, resource.TestCase{
		PreCheck:                 func() { testAccPreCheck(t) },
		ProtoV6ProviderFactories: testAccProtoV6ProviderFactories,
		Steps: []resource.TestStep{{
			Config: providerConfig() + `
data "lumos_current_user" "me" {}

data "lumos_users" "me_by_email" {
  search = data.lumos_current_user.me.email
  exact_match = true
}
`,
			Check: resource.ComposeAggregateTestCheckFunc(
				resource.TestCheckResourceAttr("data.lumos_users.me_by_email", "users.#", "1"),
				resource.TestCheckResourceAttrPair(
					"data.lumos_users.me_by_email", "users.0.id",
					"data.lumos_current_user.me", "id",
				),
			),
		}},
	})
}
